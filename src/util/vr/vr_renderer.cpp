// Debug file logging for crash diagnosis
static std::ofstream s_vr_debug_log;
static void VRDebugLog(const char* msg)
{
  if (!s_vr_debug_log.is_open())
  {
    s_vr_debug_log.open("vr_debug.log", std::ios::out | std::ios::trunc);
  }
  if (s_vr_debug_log.is_open())
  {
    s_vr_debug_log << msg << std::endl;
    s_vr_debug_log.flush();  // Flush immediately to catch crashes
  }
}

